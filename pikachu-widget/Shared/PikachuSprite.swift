import SwiftUI

// MARK: - Look

enum EyeStyle: Hashable { case open, happy, closed, tired, sad, dizzy }
enum MouthStyle: Hashable { case smile, open, frown, small }

/// Everything needed to draw one frame of the pet.
struct PikachuLook: Hashable {
    var stage: PetStage
    var eyes: EyeStyle
    var mouth: MouthStyle
    var crown = false
    var pale = false
    var headOnly = false

    init(stage: PetStage, mood: PetMood, reaction: ReactionKind?, level: Int, headOnly: Bool = false) {
        let face = Self.face(mood: mood, reaction: reaction)
        self.stage = stage
        self.eyes = face.eyes
        self.mouth = face.mouth
        self.crown = level >= PetRules.crownLevel
        self.pale = mood == .sick
        self.headOnly = headOnly
    }

    /// A fresh reaction wins over the mood.
    private static func face(mood: PetMood, reaction: ReactionKind?) -> (eyes: EyeStyle, mouth: MouthStyle) {
        switch reaction {
        case .eat, .play, .love, .clean, .levelUp, .evolve:
            return (.happy, .open)
        case .refuse:
            if mood == .sleeping { return (.closed, .small) }
            return (.sad, .frown)
        case .sleep:
            return (.closed, .small)
        case .wake:
            return (.open, .smile)
        case nil:
            break
        }
        switch mood {
        case .sleeping: return (.closed, .small)
        case .sick: return (.dizzy, .frown)
        case .hungry: return (.sad, .open)
        case .dirty: return (.tired, .frown)
        case .sleepy: return (.tired, .small)
        case .sad: return (.sad, .frown)
        case .happy: return (.happy, .open)
        case .normal: return (.open, .smile)
        }
    }

    init(_ state: PetState, headOnly: Bool = false) {
        self.init(stage: state.stage, mood: state.mood, reaction: state.reaction?.kind,
                  level: state.level, headOnly: headOnly)
    }
}

// MARK: - Drawing

/// Vector Pikachu built from layers in a 100×100 box. The layer data lives in PikachuArtData.swift,
/// generated by scripts/pikachu_art.py (which also renders an HTML preview of every expression).
enum PikachuDrawing {
    static let fullBox = CGRect(x: 0, y: 0, width: 100, height: 100)
    static let headBox = CGRect(x: 4, y: 0, width: 92, height: 80)

    /// Keep the order in sync with `assemble` in scripts/pikachu_art.py.
    static func layers(for look: PikachuLook) -> [ArtLayer] {
        var l: [ArtLayer] = []
        if !look.headOnly {
            if look.stage == .pikachu { l += tail }
            l += feet + body + paws
            if look.stage == .pichu { l += collar }
        }
        l += look.stage == .pikachu ? earsPikachu : earsPichu
        l += head
        l += look.stage == .pikachu ? cheeksRed : cheeksPink
        l += nose
        switch look.eyes {
        case .open: l += eyesOpen
        case .happy: l += eyesHappy
        case .closed: l += eyesClosed
        case .tired: l += eyesTired
        case .sad: l += eyesSad
        case .dizzy: l += eyesDizzy
        }
        switch look.mouth {
        case .smile: l += mouthSmile
        case .open: l += mouthOpen
        case .frown: l += mouthFrown
        case .small: l += mouthSmall
        }
        if look.pale { l += sickLines }
        if look.crown { l += crown }
        return l
    }

    private static var cache: [PikachuLook: [ArtPaint]] = [:]
    private static let cacheLock = NSLock()

    /// Flattens layers into fills; strokes become filled outlines so everything scales together.
    /// Cached per look, since the app redraws Pikachu every animation frame.
    static func paints(for look: PikachuLook) -> [ArtPaint] {
        cacheLock.lock()
        defer { cacheLock.unlock() }
        if let cached = cache[look] { return cached }
        let out = buildPaints(for: look)
        cache[look] = out
        return out
    }

    private static func buildPaints(for look: PikachuLook) -> [ArtPaint] {
        var out: [ArtPaint] = []
        for layer in layers(for: look) {
            if let fill = layer.fill {
                out.append(ArtPaint(id: out.count, path: layer.path, color: fill))
            }
            if let stroke = layer.stroke {
                let outline = layer.path.strokedPath(StrokeStyle(lineWidth: layer.width, lineCap: .round, lineJoin: .round))
                out.append(ArtPaint(id: out.count, path: outline, color: stroke))
            }
        }
        return out
    }
}

enum ArtShape {
    case path(String)
    case ellipse(CGFloat, CGFloat, CGFloat, CGFloat)
}

struct ArtLayer {
    let path: Path
    let fill: ArtColor?
    let stroke: ArtColor?
    let width: CGFloat

    init(_ shape: ArtShape, fill: ArtColor? = nil, stroke: ArtColor? = nil, width: CGFloat = 0) {
        switch shape {
        case .path(let d):
            path = Path(svgPath: d)
        case let .ellipse(cx, cy, rx, ry):
            path = Path(ellipseIn: CGRect(x: cx - rx, y: cy - ry, width: rx * 2, height: ry * 2))
        }
        self.fill = fill
        self.stroke = stroke
        self.width = width
    }
}

struct ArtPaint: Identifiable {
    let id: Int
    let path: Path
    let color: ArtColor
}

extension Path {
    /// Parses the absolute M/L/Q/C/Z subset of SVG path data that the art script emits.
    init(svgPath d: String) {
        self.init()
        let tokens = d.split(separator: " ").map(String.init)
        var i = 0
        func number() -> CGFloat {
            defer { i += 1 }
            return i < tokens.count ? CGFloat(Double(tokens[i]) ?? 0) : 0
        }
        func point() -> CGPoint {
            let x = number()
            return CGPoint(x: x, y: number())
        }
        var command = ""
        while i < tokens.count {
            if let c = tokens[i].first, c.isLetter {
                command = tokens[i]
                i += 1
            }
            switch command {
            case "M":
                move(to: point())
            case "L":
                addLine(to: point())
            case "Q":
                let control = point()
                addQuadCurve(to: point(), control: control)
            case "C":
                let c1 = point(), c2 = point()
                addCurve(to: point(), control1: c1, control2: c2)
            case "Z":
                closeSubpath()
                command = ""
            default:
                i += 1
            }
        }
    }
}

extension Color {
    /// "#RRGGBB" or "#RRGGBBAA".
    init(hex: String) {
        let v = UInt64(hex.dropFirst(), radix: 16) ?? 0
        let hasAlpha = hex.count == 9
        let rgb = hasAlpha ? v >> 8 : v
        self.init(.sRGB,
                  red: Double((rgb >> 16) & 0xFF) / 255,
                  green: Double((rgb >> 8) & 0xFF) / 255,
                  blue: Double(rgb & 0xFF) / 255,
                  opacity: hasAlpha ? Double(v & 0xFF) / 255 : 1)
    }
}

// MARK: - Rendering

/// Draws a path defined in `viewBox` coordinates, scaled to fit the rect. Plain `Shape`s render
/// everywhere, including widgets and the Dynamic Island.
struct ViewBoxShape: Shape {
    let path: Path
    let viewBox: CGRect

    func path(in rect: CGRect) -> Path {
        let scale = min(rect.width / viewBox.width, rect.height / viewBox.height)
        let transform = CGAffineTransform(translationX: rect.midX - viewBox.midX * scale,
                                          y: rect.midY - viewBox.midY * scale)
            .scaledBy(x: scale, y: scale)
        return path.applying(transform)
    }
}

struct PikachuSprite: View {
    let look: PikachuLook

    var body: some View {
        let box = look.headOnly ? PikachuDrawing.headBox : PikachuDrawing.fullBox
        ZStack {
            ForEach(PikachuDrawing.paints(for: look)) { paint in
                ViewBoxShape(path: paint.path, viewBox: box)
                    .fill(paint.color.color(pale: look.pale))
            }
        }
        .aspectRatio(box.width / box.height, contentMode: .fit)
        .accessibilityLabel(look.stage.displayName)
    }
}
